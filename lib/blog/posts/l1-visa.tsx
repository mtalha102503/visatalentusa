      <p>
        Petition approval and a visa are two different things, and confusing
        them causes missed trips. USCIS approves the <em>petition</em> and
        grants L-1 <em>status</em>. Only a U.S. consulate abroad issues the
        L-1 <em>visa</em> — the stamp that lets you board a plane and seek
        admission. If you are already in the United States and change status
        to L-1, you hold valid status but no visa: the first departure means
        a consular interview before you can return.
      </p>
