      <p>
        The transition deserves a closer look, because it is the part
        most often misstated. Under the rule&rsquo;s transition
        provision, an F or J nonimmigrant admitted for D/S before the
        effective date, and maintaining valid status on that date, may
        remain until the later of the employment authorization
        document expiration date or the program end date on the I-20
        or DS-2019 — but not beyond four years from September 15,
        2026, plus 60 days for F-1 students (November 14, 2030) and
        30 days for J-1 exchange visitors (October 15, 2030). The
        &ldquo;later of&rdquo; wording matters: whichever date is
        later, the EAD expiry or the program end date, controls. And
        the transition is lost by travel: an F or J nonimmigrant who
        departs before the effective date and returns after it would
        not be admitted for D/S at all.
      </p>
